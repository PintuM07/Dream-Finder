const express = require('express');
const router = express.Router();
const fs = require('fs');
const path = require('path');
const { spawn } = require('child_process');

const accountsPath = path.join(__dirname, '../data/accounts.json');
// Resolve automation/.env relative to project root (handles any CWD)
const projectRoot = path.resolve(__dirname, '../../');
const automationEnvPath = path.join(projectRoot, 'automation', '.env');

function getAccounts() {
  try {
    if (!fs.existsSync(accountsPath)) return [];
    return JSON.parse(fs.readFileSync(accountsPath, 'utf8'));
  } catch {
    return [];
  }
}

function saveAccounts(accounts) {
  fs.writeFileSync(accountsPath, JSON.stringify(accounts, null, 2));
  updateAutomationEnv(accounts);
}

function updateAutomationEnv(accounts) {
  const linkedin = accounts.find(a => a.platform === 'linkedin') || {};
  const naukri = accounts.find(a => a.platform === 'naukri') || {};

  let envContent = `# Auto-generated by Job Agent Portal\n`;
  envContent += `LINKEDIN_EMAIL=${linkedin.username || ''}\n`;
  envContent += `LINKEDIN_PASSWORD=${linkedin.password || ''}\n`;
  envContent += `NAUKRI_EMAIL=${naukri.username || ''}\n`;
  envContent += `NAUKRI_PASSWORD=${naukri.password || ''}\n`;
  envContent += `GEMINI_API_KEY=${process.env.GEMINI_API_KEY || ''}\n`;
  envContent += `BACKEND_URL=http://localhost:5000/api\n`;
  envContent += `MIN_MATCH_SCORE=50\n`;
  envContent += `MAX_APPLY_PER_RUN=10\n`;
  envContent += `JOB_KEYWORDS=React Developer,Full Stack Engineer,Software Developer\n`;
  envContent += `JOB_LOCATION=India\n`;
  envContent += `HEADLESS=false\n`;

  try {
    const automationDir = path.dirname(automationEnvPath);
    if (fs.existsSync(automationDir)) {
      fs.writeFileSync(automationEnvPath, envContent);
      console.log('[Accounts] automation/.env synced');
    } else {
      console.warn('[Accounts] automation/ folder not found, skipping .env sync');
    }
  } catch (e) {
    console.warn('[Accounts] Could not write automation/.env:', e.message);
  }
}

// GET /api/accounts - List all saved authentication accounts
router.get('/', (req, res) => {
  const accounts = getAccounts().map(acc => ({
    id: acc.id,
    platform: acc.platform,
    label: acc.label,
    username: acc.username,
    status: acc.status || 'Active',
    lastSync: acc.lastSync || null
  }));
  res.json(accounts);
});

// POST /api/accounts - Add or update account credentials
router.post('/', (req, res) => {
  try {
    const { platform, label, username, password } = req.body;
    if (!platform || !username || !password) {
      return res.status(400).json({ error: 'Platform, username/email, and password are required.' });
    }

    let accounts = getAccounts();
    const existingIndex = accounts.findIndex(a => a.platform === platform && a.username === username);

    const accountData = {
      id: existingIndex >= 0 ? accounts[existingIndex].id : Date.now().toString(),
      platform,
      label: label || `${platform.toUpperCase()} (${username})`,
      username,
      password,
      status: 'Active',
      updatedAt: new Date().toISOString()
    };

    if (existingIndex >= 0) {
      accounts[existingIndex] = accountData;
    } else {
      accounts.push(accountData);
    }

    saveAccounts(accounts);
    res.json({ success: true, account: { ...accountData, password: undefined } });
  } catch (error) {
    res.status(500).json({ error: error.message });
  }
});

// DELETE /api/accounts/:id - Remove saved account credentials
router.delete('/:id', (req, res) => {
  try {
    let accounts = getAccounts();
    accounts = accounts.filter(a => a.id !== req.params.id);
    saveAccounts(accounts);
    res.json({ success: true });
  } catch (error) {
    res.status(500).json({ error: error.message });
  }
});

// POST /api/accounts/run-automation - Launch the Naukri/LinkedIn auto-apply bot
router.post('/run-automation', (req, res) => {
  try {
    const { platform } = req.body;

    // Choose script based on platform
    let scriptPath;
    if (platform === 'naukri') {
      scriptPath = path.join(projectRoot, 'automation', 'naukri-auto.js');
    } else {
      scriptPath = path.join(projectRoot, 'automation', 'run-all.js');
    }

    const flags = [];
    if (platform === 'linkedin') flags.push('--linkedin');
    if (platform === 'naukri') flags.push('--naukri');

    const botProcess = spawn('node', [scriptPath, ...flags], {
      cwd: path.join(projectRoot, 'automation'),
      detached: true,
      stdio: 'ignore',
      env: {
        ...process.env,
        HEADLESS: 'false',
        BACKEND_URL: 'http://localhost:5000/api',
      },
    });

    botProcess.unref();

    const pid = botProcess.pid;
    console.log(`[Automation] Launched ${platform || 'all'} bot, PID: ${pid}`);

    res.json({
      success: true,
      pid,
      message: `🚀 Auto-apply bot launched for ${platform || 'all platforms'}! Check http://localhost:3000/applications for results.`,
    });
  } catch (error) {
    console.error('[Automation] Failed to launch:', error.message);
    res.status(500).json({ error: error.message });
  }
});

module.exports = router;

